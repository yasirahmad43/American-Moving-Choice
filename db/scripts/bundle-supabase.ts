/**
 * Writes db/out/supabase/NNN_name.sql for each migration and 999_seed.sql from the demo seed, each
 * wrapped to run as amc_app with objects in schema amc (build plan §10):
 *
 *   set local role amc_app;
 *   set local search_path = amc, public, extensions;
 *   <sql>
 *
 * `set local` needs a transaction: apply each file in one (Supabase apply_migration, a single
 * multi-statement execute_sql call, or psql --single-transaction all do). Migration files end by
 * recording themselves in schema_migrations so db:migrate can apply later migrations on top.
 *
 * The seed is checked before it is bundled, because the bundle is what gets deployed: it must have
 * been built by the current db/seed/build.ts, with the admin's TOTP enrolled
 * (SEED_ADMIN_TOTP_SECRET), the apps' HMAC_SECRET and a public WEB_URL, and no password hash may
 * match a password written down in the repository. Rebuild the seed with the deployment values
 * (pnpm db:seed:build) when a check fails.
 *
 * Usage: pnpm db:bundle:supabase [--skip-seed]
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import bcrypt from "bcryptjs";
import { KNOWN_PASSWORDS, builderSha256, seedMetaFile, type SeedMeta } from "../seed/build";
import { SCHEMA_MIGRATIONS_DDL, listMigrations, seedBody, seedFile } from "./lib";

export const supabaseOutDir = fileURLToPath(new URL("../out/supabase/", import.meta.url));

const PRELUDE = "set local role amc_app;\nset local search_path = amc, public, extensions;\n";
const quote = (text: string): string => `'${text.replaceAll("'", "''")}'`;

function wrap(source: string, sql: string, trailer = ""): string {
  return `-- Generated by db/scripts/bundle-supabase.ts from ${source}. Do not edit.\n${PRELUDE}\n${sql.trimEnd()}\n${trailer}`;
}

/** Problems that make a built seed unfit to deploy; empty when it may be bundled. */
export async function deployableSeedProblems(seedSql: string, meta: SeedMeta | null): Promise<string[]> {
  const problems: string[] = [];
  if (!meta) return ["db/seed/out/demo-seed.meta.json is missing: the seed predates the current builder"];
  if (meta.builderSha256 !== builderSha256()) problems.push("the seed was built by an older db/seed/build.ts");
  if (!meta.adminTotpEnrolled) problems.push("the admin's TOTP is not enrolled (set SEED_ADMIN_TOTP_SECRET and APP_ENCRYPTION_KEY)");
  if (meta.hmacSecretIsDevDefault) problems.push("contact hashes use the public development secret (set HMAC_SECRET to the apps' value)");
  if (/^https?:\/\/(localhost|127\.0\.0\.1)(:|$)/.test(meta.webUrl)) problems.push("demo messages link to localhost (set WEB_URL to the public site)");
  const hashes = seedSql.match(/\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}/g) ?? [];
  if (hashes.length === 0) problems.push("no password hashes found in the seed");
  for (const hash of hashes) {
    for (const known of KNOWN_PASSWORDS) {
      if (await bcrypt.compare(known, hash)) problems.push("a seeded password is one written down in the repository");
    }
  }
  return problems;
}

/** Returns the paths it wrote. */
export async function bundleSupabase(options: { skipSeed?: boolean } = {}): Promise<string[]> {
  const hasSeed = existsSync(seedFile) && !options.skipSeed;
  if (!existsSync(seedFile) && !options.skipSeed) {
    throw new Error("db/seed/out/demo-seed.sql not found: run pnpm db:seed:build first, or pass --skip-seed");
  }
  let seedSql = "";
  if (hasSeed) {
    seedSql = readFileSync(seedFile, "utf8");
    const meta = existsSync(seedMetaFile) ? (JSON.parse(readFileSync(seedMetaFile, "utf8")) as SeedMeta) : null;
    const problems = await deployableSeedProblems(seedSql, meta);
    if (problems.length) {
      throw new Error(`The built seed can't be deployed:\n${problems.map((p) => `  - ${p}`).join("\n")}\nRebuild it with the deployment values (pnpm db:seed:build), or pass --skip-seed.`);
    }
  }
  rmSync(supabaseOutDir, { recursive: true, force: true });
  mkdirSync(supabaseOutDir, { recursive: true });
  const written: string[] = [];
  const write = (name: string, content: string, mode = 0o644) => {
    const path = join(supabaseOutDir, name);
    writeFileSync(path, content, { mode });
    written.push(path);
  };
  for (const m of listMigrations()) {
    const trailer = `\n-- Record this migration for db/scripts/migrate.ts.\n${SCHEMA_MIGRATIONS_DDL};\n`
      + `insert into schema_migrations (name, sha256) values (${quote(m.name)}, ${quote(m.sha256)}) on conflict (name) do nothing;\n`;
    write(m.name, wrap(`db/migrations/${m.name}`, m.sql, trailer));
  }
  if (hasSeed) {
    // The seed holds bcrypt hashes of the demo passwords; keep the bundle private like the seed.
    write("999_seed.sql", wrap("db/seed/out/demo-seed.sql", seedBody(seedSql)), 0o600);
  }
  return written;
}

async function main(): Promise<void> {
  const skipSeed = process.argv.includes("--skip-seed");
  const written = await bundleSupabase({ skipSeed });
  for (const path of written) console.log(`Wrote ${path}`);
  if (skipSeed) console.log("Skipped 999_seed.sql (--skip-seed)");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
