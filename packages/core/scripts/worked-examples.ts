/**
 * Prints the worked examples used in docs/business-rules/shared-pricing-and-credits.md.
 * Run: pnpm --filter @amc/core examples
 * Fee inputs are assumptions to verify against the current Stripe pricing page.
 */
import { LAUNCH_POLICY_PROPOSAL as P, cardFee, effectiveCost, formatUsd as $, quoteNextSharedPurchase, simulateShared, type PriorBuyer } from "../src/index";

const CARD_PCT_BP = 290; // 2.9% (assumption — verify)
const CARD_FIXED = 30; // $0.30 (assumption — verify)

const companies: (PriorBuyer & { exclusive: number })[] = [
  { companyId: "A", sharedPrice: 4000, exclusive: 9000 },
  { companyId: "B", sharedPrice: 3500, exclusive: 8000 },
  { companyId: "C", sharedPrice: 4500, exclusive: 9500 },
  { companyId: "D", sharedPrice: 3000, exclusive: 7500 },
  { companyId: "E", sharedPrice: 5000, exclusive: 10000 },
];

function example(n: number, cap: number) {
  const buyers = companies.slice(0, n);
  const sim = simulateShared(buyers, cap, P);
  const out: string[] = [];
  out.push(`#### ${n} buyer${n > 1 ? "s" : ""} (consumer limit ${cap})`);
  out.push("");
  // Step log
  const prior: PriorBuyer[] = [];
  out.push("| Step | Buyer (shared price) | Charged now | Credits issued to earlier buyers |");
  out.push("|---|---|---|---|");
  for (const b of buyers) {
    const q = quoteNextSharedPurchase(prior, b.sharedPrice, cap, P);
    const credits = q.credits.length ? q.credits.map((c) => `${c.companyId} +${$(c.amount)}`).join(", ") : "—";
    out.push(`| ${q.position} | ${b.companyId} (${$(b.sharedPrice)}) | ${$(q.charge)} | ${credits} |`);
    prior.push(b);
  }
  out.push("");
  out.push("| Buyer | Shared price | Charged | Credits received | Net cost | Net as % of own price |");
  out.push("|---|---|---|---|---|---|");
  for (const r of sim.rows) {
    out.push(`| ${r.companyId} | ${$(r.sharedPrice)} | ${$(r.charged)} | ${$(r.creditsReceived)} | ${$(r.netCost)} | ${((r.netCost / r.sharedPrice) * 100).toFixed(1)}% |`);
  }
  const fees = sim.rows.reduce((s, r) => s + cardFee(r.charged, CARD_PCT_BP, CARD_FIXED), 0);
  out.push("");
  out.push(`Platform: gross charges ${$(sim.grossCharges)} − credits ${$(sim.creditsIssued)} = **net revenue ${$(sim.netRevenue)}**; ` +
    `est. card fees if every charge is card-funded ${$(fees)} → **net after fees ${$(sim.netRevenue - fees)}** ` +
    `(fees = ${((fees / sim.netRevenue) * 100).toFixed(1)}% of net revenue).`);
  out.push("");
  return out.join("\n");
}

const lines: string[] = [];
lines.push(`<!-- generated by packages/core/scripts/worked-examples.ts; policy ${P.version}; factors ${P.factorsBp.map((f) => f / 100 + "%").join(" / ")} -->`);
for (const [n, cap] of [[1, 3], [2, 3], [3, 3], [5, 5]] as const) lines.push(example(n, cap));

// Equal-price ladder
lines.push("#### Ladder for five companies that all have a $40.00 shared price");
lines.push("");
lines.push("| Buyers so far | New buyer pays | Each earlier buyer's credit at this step | Every buyer's net cost now | Platform net revenue |");
lines.push("|---|---|---|---|---|");
for (let n = 1; n <= 5; n++) {
  const step = n === 1 ? "—" : $(effectiveCost(4000, n - 1, P) - effectiveCost(4000, n, P));
  lines.push(`| ${n} | ${$(effectiveCost(4000, n, P))} | ${step} | ${$(effectiveCost(4000, n, P))} | ${$(effectiveCost(4000, n, P) * n)} |`);
}
lines.push("");

// Comparison of policy options at n buyers (same five companies)
lines.push("#### Platform net revenue by policy option (companies A–E above, before payment fees)");
lines.push("");
lines.push("| Buyers | A. Flat price, no credits | B. Equalizing step-down (recommended) | C. Naive split (price ÷ buyers) | D. Later-buyer discount, no credits | Exclusive alternative (first company's exclusive price) |");
lines.push("|---|---|---|---|---|---|");
for (let n = 1; n <= 5; n++) {
  const bs = companies.slice(0, n);
  const flat = bs.reduce((s, b) => s + b.sharedPrice, 0);
  const stepdown = simulateShared(bs, 5, P).netRevenue;
  const naive = bs.reduce((s, b) => s + Math.floor((b.sharedPrice + Math.floor(n / 2)) / n), 0);
  const laterDiscount = bs.reduce((s, b, i) => s + effectiveCost(b.sharedPrice, i + 1, P), 0);
  lines.push(`| ${n} | ${$(flat)} | ${$(stepdown)} | ${$(naive)} | ${$(laterDiscount)} | ${$(companies[0]!.exclusive)} |`);
}
lines.push("");

// Rounding example
const odd = simulateShared([{ companyId: "X", sharedPrice: 3333 }, { companyId: "Y", sharedPrice: 2999 }, { companyId: "Z", sharedPrice: 4001 }], 3, P);
lines.push("#### Rounding example (odd prices)");
lines.push("");
lines.push("| Buyer | Shared price | Charged | Credits | Net | Exact price × 65% |");
lines.push("|---|---|---|---|---|---|");
for (const r of odd.rows) lines.push(`| ${r.companyId} | ${$(r.sharedPrice)} | ${$(r.charged)} | ${$(r.creditsReceived)} | ${$(r.netCost)} | ${(r.sharedPrice * 0.0065).toFixed(4)} |`);
lines.push("");
console.log(lines.join("\n"));
